// Small RFC 4180-ish CSV parser (quoted fields, escaped quotes, CRLF). Returns rows keyed by lower-cased header.
export function parseCsv(text: string): Record<string, string>[] {
  const rows: string[][] = [];
  let row: string[] = [];
  let cell = "";
  let quoted = false;
  const src = text.replace(/^﻿/, "");
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (quoted) {
      if (c === '"' && src[i + 1] === '"') {
        cell += '"';
        i++;
      } else if (c === '"') quoted = false;
      else cell += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(cell);
      cell = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && src[i + 1] === "\n") i++;
      row.push(cell);
      cell = "";
      if (row.some((v) => v.trim() !== "")) rows.push(row);
      row = [];
    } else cell += c;
  }
  row.push(cell);
  if (row.some((v) => v.trim() !== "")) rows.push(row);

  const [head, ...body] = rows;
  if (!head) return [];
  const keys = head.map((h) => h.trim().toLowerCase());
  return body.map((r) => Object.fromEntries(keys.map((k, i) => [k, (r[i] ?? "").trim()])));
}

const cell = (v: unknown) => {
  const s = v === null || v === undefined ? "" : typeof v === "object" ? JSON.stringify(v) : String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

/** One dataset's rows as CSV: the observation time, then every payload field seen. */
export function datasetCsv(rows: { t: number; payload: Record<string, unknown> }[]) {
  const keys = [...new Set(rows.flatMap((r) => Object.keys(r.payload)))];
  const lines = [["observed_at", ...keys].join(",")];
  for (const r of rows) lines.push([new Date(r.t).toISOString(), ...keys.map((k) => cell(r.payload[k]))].map(cell).join(","));
  return lines.join("\n") + "\n";
}
